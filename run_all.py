"""Score every measure on every annotated explanation and summarize dev results.

Run: python run_all.py
Writes (all under outputs/):
  question_splits.json  the seed-469 question lists for train/dev/test
  scores.jsonl          one line per explanation: id, split, labels, every score
  dev_metrics.json      full dev metrics per measure and label target
  dev_summary.md        the tables used in the paper
The held-out test split is scored in scores.jsonl but never evaluated here.
"""

import argparse
import json
from pathlib import Path

import measures
from common import LABEL_FIELDS, LEVELS, SEED, SOURCE, evaluate_measure, load_split
from common import question_index, row_id

HEADER = (
    "| Measure | Version | Accuracy | Macro-F1 | MAE (ordinal) | Spearman ρ "
    "| ρ controlling length | Elementary F1 | High School F1 | Graduate F1 |\n"
    "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
)


def table(metrics, registry, target):
    lines = [HEADER]
    ordered = sorted(metrics, key=lambda m: -metrics[m][target]["accuracy"])
    for name in ordered:
        r = metrics[name][target]
        f1 = r["per_level_f1"]
        lines.append(
            f"| {name} | {registry[name][0]} | {r['accuracy']:.2%} | {r['macro_f1']:.3f} "
            f"| {r['mean_absolute_ordinal_error']:.3f} | {r['spearman_rho']:.3f} "
            f"| {r['spearman_rho_controlling_length']:.3f} | "
            + " | ".join(f"{f1[level]:.3f}" for level in LEVELS) + " |"
        )
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("outputs"))
    args = parser.parse_args()

    splits, train, dev, test, digest = load_split()
    registry = measures.build(train, dev + test)
    index = question_index(splits)
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "question_splits.json").write_text(
        json.dumps(splits, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    with (args.output / "scores.jsonl").open("w", encoding="utf-8") as out:
        for split, rows in (("train", train), ("dev", dev), ("test", test)):
            for row in rows:
                record = {
                    "id": row_id(row, index),
                    "split": split,
                    "question": row["Question"],
                    "intended": row[LABEL_FIELDS["intended"]],
                    "perceived": row[LABEL_FIELDS["perceived"]],
                }
                record.update({name: fn(row) for name, (_, fn, _) in registry.items()})
                out.write(json.dumps(record, ensure_ascii=False) + "\n")

    metrics = {
        name: evaluate_measure(train, dev, fn, higher_means_easier=easier)
        for name, (_, fn, easier) in registry.items()
    }
    (args.output / "dev_metrics.json").write_text(
        json.dumps({"source": SOURCE, "source_sha256": digest, "seed": SEED,
                    "level_order": LEVELS, "measures": metrics}, indent=2) + "\n",
        encoding="utf-8",
    )
    summary = (
        "# Dev results (generated by run_all.py)\n\n"
        f"{len(train)} train and {len(dev)} dev explanations, question split seed {SEED}. "
        "Cutoffs maximize train accuracy. Spearman ρ is computed on dev scores, "
        "oriented so that positive means harder text gets a higher level. "
        "ρ controlling length partials out word count (0 for word count itself).\n\n"
        "## Human-perceived level (primary)\n\n"
        f"{table(metrics, registry, 'perceived')}\n\n"
        "## Intended level (secondary)\n\n"
        f"{table(metrics, registry, 'intended')}\n"
    )
    (args.output / "dev_summary.md").write_text(summary, encoding="utf-8")
    print(summary)


if __name__ == "__main__":
    main()
